"""The C++ headers: I2S_Keys.hpp, the vocabulary as C++20 scoped enumerations
and constexpr tables, and I2S.hpp, the one installed header, which is that
vocabulary followed by the hand-written attributes API in include/.

Every name in the vocabulary comes from spec/i2s_keys.json, so renaming a key
in the JSON removes its enumerator and every use of the old name fails to
compile. Both headers open with the keys: namespace I2S::Attribute, one
constant per key with its full documentation block, is the first code after
the includes, which is what a reader scrolls to and an IDE shows on hover.
"""
# RTM Generated_01, Generated_02, Generated_03, Generated_04, PhiFlag_01, PhiFlag_02, ReadableHeaders_02, SingleHeader_01
from __future__ import annotations

import re
import textwrap
from collections.abc import Mapping

from ..model import DicomTag, Key, Member, Spec, SpecError, ValueRepresentation

# The hand-written sources I2S.hpp is stitched from, in the order they are
# copied: the concepts the declarations are constrained on, the public
# declarations, then the bodies. Each holds one "// BEGIN I2S.hpp" line and one
# "// END I2S.hpp" line; what lies outside them (include guards, the includes
# of each other) exists for editing the sources and is left out.
SOURCES = ("include/detail/I2S_Concepts.hpp", "include/I2S_Attributes.hpp", "include/detail/I2S_Attributes_impl.hpp")
_BEGIN = "// BEGIN I2S.hpp"
_END = "// END I2S.hpp"
_INCLUDE = re.compile(r"^#include <[^>]+>$")
_KEYS_INCLUDES = ("#include <array>", "#include <cstddef>", "#include <cstdint>", "#include <optional>",
                  "#include <string_view>")


def _banner(digest: str, sources: tuple[str, ...] = ()) -> str:
    return (
        "// =============================================================================\n"
        "// THIS FILE IS GENERATED BY generator/ (python -m generator). DO NOT EDIT BY HAND.\n"
        "// Source: " + " + ".join(("spec/i2s_header.json", "spec/i2s_keys.json") + sources) + "\n"
        f"// Witness: sha256 {digest}\n"
        "// `python -m generator --check` verifies this file matches the current spec.\n"
        "// =============================================================================\n"
    )


def _string(text: str) -> str:
    return '"' + text.replace("\\", "\\\\").replace('"', '\\"') + '"'


def _optional_string(text: str | None) -> str:
    return "std::nullopt" if text is None else f"std::string_view{{{_string(text)}}}"


def _tag(tag: DicomTag) -> str:
    return f"DicomTag{{0x{tag.group:04X}, 0x{tag.element:04X}}}"


def _comment(text: str) -> str:
    return " ".join(text.split())


def _enum(name: str, underlying: str, members: tuple[Member, ...], doc: str) -> str:
    lines = [f"/// {doc}", f"enum class {name} : {underlying} {{"]
    lines += [f"    {m.name}, ///< {_comment(m.description)}" for m in members]
    lines += ["};", ""]
    lines.append(f"inline constexpr std::array<std::string_view, {len(members)}> k{name}Names{{")
    lines += [f"    {_string(m.name)}," for m in members]
    lines += ["};", "", f"[[nodiscard]] constexpr std::string_view name({name} value) noexcept",
              "{", f"    return k{name}Names[static_cast<std::size_t>(value)];", "}", ""]
    return "\n".join(lines)


def _dicom(key: Key) -> str:
    if key.dicom is None:
        return "std::nullopt"
    sequence = "std::nullopt"
    if key.dicom.sequence is not None:
        sequence = f"DicomSequence{{{_string(key.dicom.sequence.keyword)}, {_tag(key.dicom.sequence.tag)}}}"
    return (f"DicomAttribute{{{_string(key.dicom.keyword)}, {_tag(key.dicom.tag)}, "
            f"{_string(key.dicom.vr)}, {sequence}}}")


def _phi_flag(key: Key) -> str:
    if key.phi_flag is None:
        return "std::nullopt"
    return f"PhiFlag{{Key::{key.phi_flag.key}, {'true' if key.phi_flag.absent_means_phi else 'false'}}}"


def _row(key: Key) -> str:
    maximum = "std::nullopt" if key.multiplicity.maximum is None else str(key.multiplicity.maximum)
    return (
        f"    KeyInfo{{Key::{key.name}, {_string(key.name)}, {_optional_string(key.short_name)},\n"
        f"            {_dicom(key)},\n"
        f"            ValueType::{key.value_type}, Vr::{key.vr}, Multiplicity{{{key.multiplicity.minimum}, {maximum}}}, "
        f"IdentityClass::{key.identity},\n"
        f"            {_phi_flag(key)}, {'true' if key.deprecated else 'false'}}},"
    )


def _vr_row(vr: ValueRepresentation) -> str:
    return (f"    VrInfo{{Vr::{vr.name}, {_string(vr.name)}, {vr.max_length}u, "
            f"{'true' if vr.length_unit == 'characters' else 'false'}, "
            f"{'true' if vr.multiple_values else 'false'}, {_string(vr.example)}}},")


def _doc_block(key: Key) -> list[str]:
    """The constant a developer types, with the documentation an IDE shows on hover."""
    if key.dicom is None:
        dicom = "none: I2S diverges from DICOM"
    else:
        dicom = f"{key.dicom.keyword} {key.dicom.tag}"
        if key.dicom.sequence is not None:
            dicom += f", in {key.dicom.sequence.keyword} {key.dicom.sequence.tag} items"
    short = f" (short name {key.short_name})" if key.short_name else ""
    lines = [
        f"/// {key.name}{short}: {_comment(key.description)}",
        f"/// Value type {key.value_type}, written as the DICOM VR {key.vr}, multiplicity {key.multiplicity.text}.",
        f"/// DICOM: {dicom}. Identity class: {key.identity}." + (" Deprecated." if key.deprecated else ""),
        f"inline constexpr TypedKey<Key::{key.name}> {key.name}{{}};",
    ]
    if key.short_name is not None:
        lines += [f"/// {key.short_name}: the short name of {key.name}, the same key.",
                  f"inline constexpr TypedKey<Key::{key.name}> {key.short_name}{{}};"]
    return lines


def _vocabulary(keys: tuple[Key, ...]) -> str:
    """The keys, first: the Key enumeration (names only, so it stays a few
    lines) and TypedKey, which the constants are declared with, then namespace
    I2S::Attribute, one documented constant per key."""
    enumerators = "\n".join(textwrap.wrap(", ".join(k.name for k in keys) + ",", 96,
                                          initial_indent="    ", subsequent_indent="    "))
    constants = "\n".join(line for k in keys for line in _doc_block(k))
    return f"""/// Every key, in the order the specification defines them. Each is
/// documented on its constant in namespace I2S::Attribute, below.
enum class Key : std::uint16_t {{
{enumerators}
}};

/// A key as a type, so a value written under it is checked at compile time.
template <Key K>
struct TypedKey {{
    static constexpr Key key = K;
}};

/// The keys a program writes: attributes[I2S::Attribute::Manufacturer] = "Leica";
/// One constant per key, its short name (the same key) right after it.
namespace Attribute {{

{constants}

}} // namespace Attribute"""


def _keys_body(spec: Spec) -> str:
    """namespace I2S: the keys, then the version, then every table and lookup."""
    vr_names = "\n".join(f"    {vr.name}, ///< {_comment(vr.description)}" for vr in spec.value_representations)
    vr_rows = "\n".join(_vr_row(vr) for vr in spec.value_representations)
    rows = "\n".join(_row(k) for k in spec.keys)
    return f"""namespace I2S {{

{_vocabulary(spec.keys)}

// =============================================================================
// The version, and the tables behind the vocabulary: VRs, value types,
// identity classes, each key's facts (kKeys), and the lookups over them.
// =============================================================================

/// The version of the {spec.name} this header was generated from.
inline constexpr std::uint16_t kVersionMajor = {spec.version.major};
inline constexpr std::uint16_t kVersionMinor = {spec.version.minor};
/// This version as IFE's ATTRIBUTES.VERSION carries it under METADATA_I2S:
/// major << 8 | minor, so 0.1 is 0x0001 and 1.0 is 0x0100 (decided 2026-11-25).
inline constexpr std::uint16_t kIfeAttributesVersion = static_cast<std::uint16_t>(kVersionMajor << 8 | kVersionMinor);
inline constexpr bool kIsDraft = {'true' if spec.status == 'draft' else 'false'};

/// The DICOM value representations I2S writes a value as (PS3.5 section 6.2).
enum class Vr : std::uint8_t {{
{vr_names}
}};

/// One VR as I2S writes it. max_length counts characters when
/// counts_characters is true, and UTF-8 bytes otherwise.
struct VrInfo {{
    Vr vr;
    std::string_view name;
    std::uint32_t max_length;
    bool counts_characters;
    bool multiple_values;
    std::string_view example;
}};

/// Indexed by Vr.
inline constexpr std::array<VrInfo, {len(spec.value_representations)}> kVrs{{{{
{vr_rows}
}}}};

[[nodiscard]] constexpr const VrInfo& info(Vr vr) noexcept
{{
    return kVrs[static_cast<std::size_t>(vr)];
}}

{_enum("ValueType", "std::uint8_t", spec.value_types, "What a key's value is.")}
{_enum("IdentityClass", "std::uint8_t", spec.identity_classes, "Whether a key's value can identify an individual.")}
inline constexpr std::size_t kKeyCount = {len(spec.keys)};

struct DicomTag {{
    std::uint16_t group;
    std::uint16_t element;
    friend constexpr bool operator==(const DicomTag&, const DicomTag&) noexcept = default;
}};

/// The DICOM sequence whose items carry the attribute, one value per item.
struct DicomSequence {{
    std::string_view keyword;
    DicomTag tag;
}};

struct DicomAttribute {{
    std::string_view keyword;
    DicomTag tag;
    std::string_view vr;
    std::optional<DicomSequence> sequence;
}};

/// How many values a key holds; no maximum means no upper bound.
struct Multiplicity {{
    std::uint16_t minimum;
    std::optional<std::uint16_t> maximum;
}};

/// The BOOLEAN key that states, per file, whether a key's value is protected
/// health information, and what a reader and a de-identifier assume when the
/// flag is absent from a file that carries the key.
struct PhiFlag {{
    Key key;
    bool absent_means_phi;
}};

struct KeyInfo {{
    Key key;
    std::string_view name;
    std::optional<std::string_view> short_name;
    /// std::nullopt where I2S diverges from DICOM and DICOM has no such attribute.
    std::optional<DicomAttribute> dicom;
    ValueType value_type;
    Vr vr;
    Multiplicity multiplicity;
    IdentityClass identity;
    /// std::nullopt where no flag qualifies the key's identity class per file.
    std::optional<PhiFlag> phi_flag;
    bool deprecated;
}};

/// Indexed by Key: kKeys[static_cast<std::size_t>(key)] describes key.
inline constexpr std::array<KeyInfo, kKeyCount> kKeys{{{{
{rows}
}}}};

static_assert(
    [] {{
        for (std::size_t index = 0; index < kKeys.size(); ++index) {{
            if (static_cast<std::size_t>(kKeys[index].key) != index) {{
                return false;
            }}
        }}
        return true;
    }}(),
    "kKeys must be indexed by Key");

[[nodiscard]] constexpr const KeyInfo& info(Key key) noexcept
{{
    return kKeys[static_cast<std::size_t>(key)];
}}

[[nodiscard]] constexpr std::string_view name(Key key) noexcept
{{
    return info(key).name;
}}

/// The key whose name or short name is `text`, or std::nullopt when I2S
/// defines no such key. Names are case-sensitive, as DICOM keywords are.
[[nodiscard]] constexpr std::optional<Key> key_from_name(std::string_view text) noexcept
{{
    for (const KeyInfo& entry : kKeys) {{
        if (entry.name == text || entry.short_name == text) {{
            return entry.key;
        }}
    }}
    return std::nullopt;
}}

}} // namespace I2S"""


def emit_header(spec: Spec, digest: str) -> str:
    """I2S_Keys.hpp: the vocabulary alone, which the sources in include/ are edited against."""
    includes = "\n".join(_KEYS_INCLUDES)
    return f"{_banner(digest)}\n#ifndef I2S_KEYS_HPP\n#define I2S_KEYS_HPP\n\n{includes}\n\n{_keys_body(spec)}\n\n#endif // I2S_KEYS_HPP\n"


def _region(path: str, text: str) -> tuple[list[str], str]:
    """A source's lines between its markers: its standard includes, and the rest."""
    lines = text.splitlines()
    if lines.count(_BEGIN) != 1 or lines.count(_END) != 1 or lines.index(_BEGIN) > lines.index(_END):
        raise SpecError(f"{path}: needs one '{_BEGIN}' line and one '{_END}' line after it")
    region = lines[lines.index(_BEGIN) + 1:lines.index(_END)]
    includes = [line for line in region if _INCLUDE.match(line)]
    body = "\n".join(line for line in region if not _INCLUDE.match(line))
    return includes, re.sub(r"\n{3,}", "\n\n", body).strip("\n")


def emit_single_header(spec: Spec, digest: str, sources: Mapping[str, str]) -> str:
    """I2S.hpp: the vocabulary, the public declarations, then the implementation,
    whose non-template bodies compile only where I2S_IMPLEMENTATION is defined.
    sources maps each path in SOURCES to its text; raises SpecError naming a
    source whose markers are missing."""
    regions = {path: _region(path, sources[path]) for path in SOURCES}
    includes = "\n".join(sorted({*_KEYS_INCLUDES, *(line for found, _ in regions.values() for line in found)}))
    parts = [f"""{_banner(digest, SOURCES)}
// One header: #define I2S_IMPLEMENTATION in exactly one .cpp of a program,
// before #include <I2S.hpp>, to compile the function bodies there.
#ifndef I2S_HPP
#define I2S_HPP

{includes}

{_keys_body(spec)}"""]
    for path, (_, body) in regions.items():
        parts.append(f"// =============================================================================\n"
                     f"// From {path}\n"
                     f"// =============================================================================\n\n{body}")
    return "\n\n".join(parts) + "\n\n#endif // I2S_HPP\n"
