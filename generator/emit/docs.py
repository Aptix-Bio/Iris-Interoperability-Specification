"""i2s_specification.md: the specification as a readable document."""
# RTM Document_01
from __future__ import annotations

from ..model import Key, Member, Spec


def _cell(text: str) -> str:
    return " ".join(text.split()).replace("|", "\\|")


def _members(title: str, members: tuple[Member, ...]) -> list[str]:
    lines = [f"## {title}", "", "| Name | Since | Meaning |", "|---|---|---|"]
    lines += [f"| `{m.name}` | {m.since} | {_cell(m.description)} |" for m in members]
    return lines + [""]


def _dicom_cell(key: Key) -> str:
    if key.dicom is None:
        return "none (I2S diverges)"
    cell = f"`{key.dicom.keyword}` {key.dicom.tag} {key.dicom.vr}"
    if key.dicom.sequence is not None:
        cell += f", in each item of `{key.dicom.sequence.keyword}` {key.dicom.sequence.tag}"
    return cell


def _key_section(key: Key) -> list[str]:
    lines = [f"### {key.name}", ""]
    if key.deprecated is not None:
        lines += [f"**Deprecated:** {key.deprecated}", ""]
    lines += [key.description, ""]
    lines += [f"- **Short name:** {f'`{key.short_name}`' if key.short_name else 'none'}"]
    lines += [f"- **DICOM:** {_dicom_cell(key)}"]
    if key.dicom is not None:
        lines += [f"- **DICOM verified against:** {key.dicom.verified}"]
    lines += [f"- **Value type:** `{key.value_type}` · **Multiplicity:** {key.multiplicity.text}"]
    lines += [f"- **Identity class:** `{key.identity}`"]
    if key.identity_note is not None:
        lines += [f"- **Identity note:** {key.identity_note}"]
    if key.phi_flag is not None:
        absent = "is" if key.phi_flag.absent_means_phi else "is not"
        lines += [f"- **PHI flag:** [{key.phi_flag.key}](#{key.phi_flag.key.lower()}). When this key is present "
                  f"and the flag is absent, a reader and a de-identifier shall treat this key's value as one that "
                  f"{absent} protected health information."]
    return lines + [""]


def emit_document(spec: Spec, digest: str) -> str:
    lines = [
        "<!--",
        "THIS FILE IS GENERATED BY generator/ (python -m generator). DO NOT EDIT BY HAND.",
        "Source: spec/i2s_header.json + spec/i2s_keys.json",
        f"Witness: sha256 {digest}",
        "-->",
        "",
        f"# {spec.name} ({spec.abbreviation}) {spec.version}",
        "",
        f"Status: **{spec.status}**. Repository: {spec.repository}",
        "",
        "## Revision history",
        "",
        "| Version | Status | Authors | Summary |",
        "|---|---|---|---|",
    ]
    lines += [f"| {r.version} | {r.status} | {', '.join(r.authors)} | {_cell(r.summary)} |" for r in spec.revisions]
    lines += [""]
    lines += _members("Value types", spec.value_types)
    lines += _members("Identity classes", spec.identity_classes)
    lines += ["## Keys", "", "| Key | Short name | DICOM | Value type | Multiplicity | Identity | Since |",
              "|---|---|---|---|---|---|---|"]
    lines += [
        f"| [{k.name}](#{k.name.lower()}) | {k.short_name or ''} | {_dicom_cell(k)} | `{k.value_type}` "
        f"| {k.multiplicity.text} | `{k.identity}` | {k.since} |"
        for k in spec.keys
    ]
    lines += [""]
    for key in spec.keys:
        lines += _key_section(key)
    return "\n".join(lines).rstrip() + "\n"
