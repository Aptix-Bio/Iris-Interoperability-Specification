"""AsciiDoc emission for the I2S specification document, as IFE's is.

One file per item. The hand-written narrative (spec/i2s_spec.adoc) pulls each
in with Asciidoctor's native include::, so every table and key section in the
published document comes from spec/*.json and cannot disagree with the header
an implementation compiles against. Emitted into generated_docs/:

    attributes.adoc        document attributes from spec/i2s_header.json
    revision_history.adoc  one entry per revision
    value_types.adoc       the value types, with their examples
    identity_classes.adoc  the identity classes
    keys_table.adoc        every key, one row each
    key_sections.adoc      one section per key

Every file but attributes.adoc opens with a //// DO-NOT-EDIT banner carrying
the witness hash; attributes.adoc carries it as // line comments, since a
block comment would end the document header.
"""
# RTM Document_02
from __future__ import annotations

from ..model import Key, Member, Spec

def _banner(digest: str) -> list[str]:
    return [
        "////",
        "Generated by `python3 -m generator` from spec/*.json. DO NOT EDIT BY HAND.",
        f"Witness: sha256 {digest}",
        "`python3 -m generator --check` verifies this file matches the current spec.",
        "////",
        "",
    ]


def _cell(text: str) -> str:
    return " ".join(text.split()).replace("|", "\\|")


def anchor(key: Key) -> str:
    return f"i2s-key-{key.name}"


def _dicom(key: Key) -> str:
    if key.dicom is None:
        return "none (I2S diverges)"
    text = f"`{key.dicom.keyword}` {key.dicom.tag} {key.dicom.vr}"
    if key.dicom.sequence is not None:
        text += f", in each item of `{key.dicom.sequence.keyword}` {key.dicom.sequence.tag}"
    return text


def _attributes(spec: Spec, digest: str) -> str:
    newest = spec.revisions[-1]
    return "\n".join([
        "// Generated from spec/i2s_header.json by `python3 -m generator`. DO NOT EDIT BY HAND.",
        f"// Witness: sha256 {digest}",
        "// No blank line or block comment below: either would end the document header.",
        f":revnumber: {spec.version}",
        f":revdate: {newest.date}",
        f":revremark: {spec.status}",
        f":author: {', '.join(newest.authors)}",
        f":i2s-abbreviation: {spec.abbreviation}",
        f":repository: {spec.repository}",
    ]) + "\n"


def _revision_history(spec: Spec, digest: str) -> str:
    lines = _banner(digest)
    for r in spec.revisions:
        lines += [f"*Version {r.version}* ({r.status}, {r.date}), {', '.join(r.authors)}::", r.summary, ""]
    return "\n".join(lines).rstrip() + "\n"


def _members(title: str, members: tuple[Member, ...], digest: str) -> str:
    examples = any(m.example is not None for m in members)
    lines = _banner(digest) + [f".{title}"]
    lines += ['[cols="1,1,2,4",options="header"]' if examples else '[cols="1,1,6",options="header"]', "|==="]
    lines += ["|Name |Since |Example |Meaning" if examples else "|Name |Since |Meaning", ""]
    for m in members:
        example = f"|`{_cell(m.example)}` " if m.example is not None else ""
        lines.append(f"|`{m.name}` |{m.since} {example}|{_cell(m.description)}")
    return "\n".join(lines + ["|==="]) + "\n"


def _keys_table(spec: Spec, digest: str) -> str:
    lines = _banner(digest) + [".Keys", '[cols="3,2,3,2,1,2,1",options="header"]', "|===",
                               "|Key |Short name |DICOM |Value type |Multiplicity |Identity |Since", ""]
    for k in spec.keys:
        lines.append(
            f"|<<{anchor(k)},`{k.name}`>> |{f'`{k.short_name}`' if k.short_name else ''} |{_dicom(k)} "
            f"|`{k.value_type}` |{k.multiplicity.text} |`{k.identity}` |{k.since}"
        )
    return "\n".join(lines + ["|==="]) + "\n"


def _key_sections(spec: Spec, digest: str) -> str:
    lines = _banner(digest)
    for k in spec.keys:
        lines += [f"[[{anchor(k)}]]", f"=== {k.name}", ""]
        if k.deprecated is not None:
            lines += [f"WARNING: Deprecated. {k.deprecated}", ""]
        lines += [k.description, ""]
        lines += [f"Short name:: {f'`{k.short_name}`' if k.short_name else 'none'}"]
        lines += [f"DICOM:: {_dicom(k)}"]
        lines += [f"Value type:: `{k.value_type}`, multiplicity {k.multiplicity.text}"]
        lines += [f"Identity class:: `{k.identity}`"]
        if k.identity_note is not None:
            lines += [f"Identity note:: {k.identity_note}"]
        if k.phi_flag is not None:
            absent = "shall treat this key's value as protected health information" if k.phi_flag.absent_means_phi \
                else "shall treat this key's value as identifying no individual"
            lines += [f"PHI flag:: <<i2s-key-{k.phi_flag.key},`{k.phi_flag.key}`>>. When this key is present and "
                      f"the flag is absent, a reader and a de-identifier {absent}."]
        if k.dicom is not None:
            sources = "; ".join(f"{v.url}[{v.title}], read {v.read}" for v in k.dicom.verified)
            lines += [f"DICOM verified against:: {sources}"]
        lines += [f"Since:: {k.since}", ""]
    return "\n".join(lines).rstrip() + "\n"


def emit_documents(spec: Spec, digest: str) -> dict[str, str]:
    """File name -> AsciiDoc text. The names are the contract with
    spec/i2s_spec.adoc, which includes each one."""
    return {
        "attributes.adoc": _attributes(spec, digest),
        "revision_history.adoc": _revision_history(spec, digest),
        "value_types.adoc": _members("Value types", spec.value_types, digest),
        "identity_classes.adoc": _members("Identity classes", spec.identity_classes, digest),
        "keys_table.adoc": _keys_table(spec, digest),
        "key_sections.adoc": _key_sections(spec, digest),
    }
